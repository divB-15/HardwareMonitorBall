// ============================================================================
//  core/metric_map.h — 纯逻辑的指标映射（不 include <windows.h>）
//
//  这一层刻意与 Win32 解耦：比例映射、档位判定、数值格式化都是纯函数，
//  可以被 tests/ 下的单元测试直接链接验证，不需要开窗口。
// ============================================================================
#pragma once

#include <string>

namespace core {

// --- 比例映射（环形仪表 / 卡片进度条）---------------------------------------
// 温度统一映射到 25~105 °C：25 以下空环，105 满环。返回值 <0 表示没采到数据。
double temp_ratio(double celsius);

// 百分比直接映射 0~100。返回值 <0 表示没采到数据。
double percent_ratio(double percent);

// --- 档位（决定配色）--------------------------------------------------------
// 阈值一律按"四舍五入后的显示值"判定，保证屏幕上的数字和颜色口径一致：
// 否则 74.6 显示成 75 却还是青色，观感割裂。
enum Level {
    kNormal = 0,
    kWarn   = 1,
    kHot    = 2,
};

Level level_by_threshold(int value, int warn_at, int hot_at);

// --- 数值 -------------------------------------------------------------------
// 与显示口径一致的四舍五入（v 必须 >= 0，调用方先排除"没采到"的负值）
int round_to_int(double v);

// 球面 / 卡片上的数值文本：负值（没采到）显示 "--"，否则取整
std::wstring format_value(double v);

}  // namespace core
